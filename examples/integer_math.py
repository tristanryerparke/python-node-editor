def add(a: int, b: int) -> int:
    """Adds two numbers together and returns the result"""
    return a + b


def subtract(a: int, b: int) -> int:
    return a - b


def multiply(a: int, b: int) -> int:
    return a * b


def divide(a: int, b: int) -> float:
    return a / b


def power(a: int, b: int) -> int:
    return a**b
